#These are Strings ... series of characters which also include numbers as characters
first_name="bro"
print(first_name)
#also u can use f string or format string
print(f"hello {first_name}")
food = "pizza"
print(f"You Like {food}")
email = "bro@fake.com"
print(f"Your Email is: {email}")


#These are Integers
age = 18
print(f"You are {age} Years old")

quantity = 5
print(f"You are Buying {quantity} Items")

num_of_students = 40
print(f"Your class has {num_of_students} Students")

#   These are floats
price = 10.99
print(f"Price is ${price}")

gpa = 9.9
print(f"Your gps is: {gpa}")

distance = 5.7
print(f"You ran {distance} KM")

#These are Boolean(basically true or false)
is_student = True
print(f"Are you a Student? : {is_student}")

if is_student:
    print("You are a Student")
else:
    print("You are NOT a Student")

for_sale = False

if for_sale:
    print("This item is for Sale")
else:
    print("This item is NOT Available")

is_online = True

if is_online:
    print("ONLINE")
else:
    print("OFFLINE")










